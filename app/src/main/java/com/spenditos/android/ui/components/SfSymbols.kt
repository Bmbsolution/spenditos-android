/** Symbol stroke weight. SF Symbols at body sizes match Phosphor bold; [Light] uses Phosphor regular. */
enum class SymbolWeight { Light, Regular, Bold }

/**
 * SF Symbol names used by the iOS app, drawn with Phosphor icons (MIT), the closest open set to SF Symbols
 * (rounded strokes; regular, bold and fill weights). SF Symbols themselves may not ship outside Apple
 * platforms. Screens ported from SwiftUI keep the iOS name: `Image(systemName: "calendar.badge.clock")` is
 * `Icon(SfSymbols.icon("calendar.badge.clock"), ...)`; a `.fill` name draws the filled weight, and
 * `.ultraLight`/`.light` symbols pass [SymbolWeight.Light]. Unknown names fall back to the tag,
 * like iOS `IconMapper.defaultSymbol`.
 */
object SfSymbols {
    fun icon(name: String, weight: SymbolWeight = SymbolWeight.Regular): ImageVector {
        val base = name.removeSuffix(".fill")
        val filled = name.endsWith(".fill") || base in solidSymbols
        val phosphor = map[base] ?: "tag"
        val style = when {
            filled -> "fill"
            // SF Symbols at their usual 15-17pt sizes read as heavy as Phosphor's bold weight; Phosphor
            // regular looks hairline next to them, so it is kept for explicitly light uses only.
            weight == SymbolWeight.Light -> "regular"
            else -> "bold"
        }
        return cache.getOrPut("$phosphor-$style") { build("$phosphor-$style", PhosphorPaths.path(phosphor, style) ?: PhosphorPaths.path("tag", style)!!) }
    }

    private val cache = ConcurrentHashMap<String, ImageVector>()

    /** SF symbols whose plain (non-.fill) form is already drawn solid, like the gear. */
    private val solidSymbols = setOf("gearshape", "gearshape.2")

    private fun build(name: String, pathData: String): ImageVector =
        ImageVector.Builder(name = name, defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 256f, viewportHeight = 256f)
            .addPath(pathData = PathParser().parsePathString(pathData).toNodes(), fill = SolidColor(Color.Black))
            .build()

