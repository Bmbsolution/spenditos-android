#!/usr/bin/env python3
"""Regenerate the Phosphor category icon drawables and Kotlin catalog from `packages/types`.

Source of truth (backend repo, read-only):
  packages/types/src/domain/category-icons.ts               emoji/legacy/keyword catalog + resolver
  packages/types/assets/category-icons/{regular,duotone}/*.svg  256x256 Phosphor SVGs

Outputs (committed; re-run whenever the types package changes):
  app/src/main/res/drawable/ph_<name>.xml and ph_<name>_duotone.xml   (VectorDrawables, viewport 256)
  app/src/main/java/com/spenditos/android/ui/components/phosphor/PhosphorCategoryIconCatalog.kt

Usage:
  scripts/generate-phosphor-category-icons.py [path-to-spenditos-types-package]
The argument defaults to ../spenditos/packages/types next to this repo. Pass the backend worktree's
packages/types when it lives elsewhere.

Phosphor SVGs are plain `<path d=... [opacity=0.2]/>` shapes. Any other element (circle/rect/line/...) or
unexpected attribute makes the script fail loudly instead of silently dropping geometry.
"""
from __future__ import annotations

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DRAWABLE_DIR = REPO / "app/src/main/res/drawable"
KOTLIN_FILE = (
    REPO / "app/src/main/java/com/spenditos/android/ui/components/phosphor/PhosphorCategoryIconCatalog.kt"
)
SVG_NS = "{http://www.w3.org/2000/svg}"
ALLOWED_PATH_ATTRS = {"d", "opacity"}


def die(message: str) -> None:
    print(f"error: {message}", file=sys.stderr)
    sys.exit(1)


# ---------------------------------------------------------------- catalog parsing

def block(source: str, name: str) -> str:
    match = re.search(r"export const " + name + r"\b[^=]*=\s*(?:\{|\[)(.*?)\n(?:\}|\]);", source, re.S)
    if not match:
        die(f"cannot find {name} in category-icons.ts")
    return match.group(1)


def parse_map(source: str, name: str) -> list[tuple[str, str]]:
    """Ordered (key, value) pairs; a repeated key keeps its first position and takes the last value (JS semantics)."""
    out: dict[str, str] = {}
    for line in block(source, name).splitlines():
        match = re.match(r"\s*(?:'([^']+)'|([A-Za-z0-9_]+))\s*:\s*'([^']+)'\s*,?\s*(?://.*)?$", line)
        if match:
            out[match.group(1) or match.group(2)] = match.group(3)
        elif line.strip() and not line.strip().startswith("//"):
            die(f"unparsed line in {name}: {line!r}")
    return list(out.items())


def parse_keywords(source: str) -> list[tuple[list[str], str]]:
    out = []
    for line in block(source, "CATEGORY_NAME_KEYWORDS").splitlines():
        match = re.match(r"\s*\{\s*words:\s*\[(.*?)\],\s*icon:\s*'([^']+)'\s*\},?\s*$", line)
        if match:
            words = re.findall(r"'([^']+)'", match.group(1))
            out.append((words, match.group(2)))
        elif line.strip() and not line.strip().startswith("//"):
            die(f"unparsed keyword line: {line!r}")
    return out


def default_icon(source: str) -> str:
    match = re.search(r"DEFAULT_CATEGORY_ICON_NAME\s*=\s*'([^']+)'", source)
    if not match:
        die("cannot find DEFAULT_CATEGORY_ICON_NAME")
    return match.group(1)


# ---------------------------------------------------------------- SVG -> VectorDrawable

def convert_svg(svg_path: Path) -> str:
    root = ET.parse(svg_path).getroot()
    if root.tag != SVG_NS + "svg" or root.get("viewBox") != "0 0 256 256":
        die(f"{svg_path}: expected a 0 0 256 256 svg")
    paths = []
    for element in root:
        if element.tag != SVG_NS + "path":
            die(f"{svg_path}: unsupported element <{element.tag.replace(SVG_NS, '')}> (only <path> is converted)")
        extra = set(element.attrib) - ALLOWED_PATH_ATTRS
        if extra:
            die(f"{svg_path}: unsupported path attributes {sorted(extra)}")
        paths.append((element.attrib["d"], element.get("opacity")))
    if not paths:
        die(f"{svg_path}: no paths")
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by scripts/generate-phosphor-category-icons.py. Do not edit. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="24dp"',
        '    android:height="24dp"',
        '    android:viewportWidth="256"',
        '    android:viewportHeight="256">',
    ]
    for data, opacity in paths:
        alpha = f'\n        android:fillAlpha="{opacity}"' if opacity else ""
        lines.append(
            f'    <path\n        android:fillColor="#FF000000"{alpha}\n        android:pathData="{data}" />'
        )
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def res_name(icon: str, duotone: bool) -> str:
    return "ph_" + icon.replace("-", "_") + ("_duotone" if duotone else "")


# ---------------------------------------------------------------- Kotlin emission

def kt_string(value: str) -> str:
    out = []
    for ch in value:
        if ch in '"\\$':
            out.append("\\" + ch)
        elif ch in ("️", "‍"):
            out.append(f"\\u{ord(ch):04X}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def emit_kotlin(
    emoji: list[tuple[str, str]],
    legacy: list[tuple[str, str]],
    keywords: list[tuple[list[str], str]],
    default: str,
    names: list[str],
) -> str:
    def pairs(items: list[tuple[str, str]]) -> str:
        return "\n".join(f"        {kt_string(k)} to {kt_string(v)}," for k, v in items)

    kw = "\n".join(
        f"        Keyword(listOf({', '.join(kt_string(w) for w in words)}), {kt_string(icon)})," for words, icon in keywords
    )
    regular = "\n".join(f"        {kt_string(n)} to R.drawable.{res_name(n, False)}," for n in names)
    duotone = "\n".join(f"        {kt_string(n)} to R.drawable.{res_name(n, True)}," for n in names)
    return f"""// Generated by scripts/generate-phosphor-category-icons.py from packages/types
// (src/domain/category-icons.ts and assets/category-icons). Do not edit; re-run the script instead.
package com.spenditos.android.ui.components.phosphor

import com.spenditos.android.R

/** Catalog data mirrored from `category-icons.ts`; resolution lives in `CategoryIcons`. */
internal object PhosphorCategoryIconCatalog {{
    const val DEFAULT_ICON_NAME = {kt_string(default)}

    class Keyword(val words: List<String>, val icon: String)

    /** Emoji to Phosphor icon name (insertion order matters for the variation-selector fallback). */
    val emoji: Map<String, String> = linkedMapOf(
{pairs(emoji)}
    )

    /** Legacy SF Symbol / semantic names written by earlier iOS and web builds. */
    val legacy: Map<String, String> = linkedMapOf(
{pairs(legacy)}
    )

    /** Ordered whole-word keyword fallbacks on the category name; first match wins. */
    val keywords: List<Keyword> = listOf(
{kw}
    )

    /** Phosphor name to the Regular-weight VectorDrawable. */
    val regular: Map<String, Int> = mapOf(
{regular}
    )

    /** Phosphor name to the Duotone VectorDrawable (first path at 20% alpha). */
    val duotone: Map<String, Int> = mapOf(
{duotone}
    )
}}
"""


def main() -> None:
    types_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else REPO.parent / "spenditos/packages/types"
    ts_file = types_dir / "src/domain/category-icons.ts"
    assets = types_dir / "assets/category-icons"
    if not ts_file.is_file() or not assets.is_dir():
        die(f"{types_dir} is not a packages/types checkout (missing category-icons.ts or assets/category-icons)")

    source = ts_file.read_text(encoding="utf-8")
    emoji = parse_map(source, "CATEGORY_EMOJI_ICONS")
    legacy = parse_map(source, "CATEGORY_LEGACY_ICONS")
    keywords = parse_keywords(source)
    default = default_icon(source)

    used = {default}
    used.update(v for _, v in emoji)
    used.update(v for _, v in legacy)
    used.update(icon for _, icon in keywords)

    available = {p.stem for p in (assets / "regular").glob("*.svg")}
    if available != {p.stem for p in (assets / "duotone").glob("*.svg")}:
        die("regular and duotone asset sets differ")
    missing = sorted(used - available)
    if missing:
        die(f"catalog references icons without assets: {missing}")
    # Ship every exported asset (not just the referenced ones) so the set matches web/iOS bundles.
    names = sorted(available)

    DRAWABLE_DIR.mkdir(parents=True, exist_ok=True)
    for stale in DRAWABLE_DIR.glob("ph_*.xml"):
        stale.unlink()
    for name in names:
        for duotone in (False, True):
            svg = assets / ("duotone" if duotone else "regular") / f"{name}.svg"
            xml = convert_svg(svg)
            if duotone and "android:fillAlpha=\"0.2\"" not in xml:
                die(f"{svg}: duotone icon without a 0.2 secondary layer")
            (DRAWABLE_DIR / f"{res_name(name, duotone)}.xml").write_text(xml, encoding="utf-8")

    KOTLIN_FILE.parent.mkdir(parents=True, exist_ok=True)
    KOTLIN_FILE.write_text(emit_kotlin(emoji, legacy, keywords, default, names), encoding="utf-8")
    print(
        f"wrote {len(names) * 2} drawables, {len(emoji)} emoji, {len(legacy)} legacy names, "
        f"{len(keywords)} keyword rules -> {KOTLIN_FILE.relative_to(REPO)}"
    )


if __name__ == "__main__":
    main()
